// Self-installing Traefik route.
//
// Dokploy serves its dashboard through Traefik with a file-provider config (dokploy.yml) when a
// domain is set in "Web Server" settings. We read that file, find the router(s) pointing at the
// Dokploy service, and write our own file next to it (dokploy-plus.yml) with:
//   - HTML page loads (GET + Accept: text/html) -> Dokploy Plus (injects the loader script),
//   - /_ext/*                                  -> Dokploy Plus (modules + API),
//   - everything else untouched (still served by Dokploy's own router).
// A failover service sends pages straight to Dokploy if Dokploy Plus stops answering, and the
// file is removed when the container stops: uninstalling = removing the container.
import { existsSync, readFileSync, readdirSync, renameSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { load as yamlLoad } from "./vendor/js-yaml.mjs";

const DIR = process.env.TRAEFIK_DYNAMIC_DIR || "/etc/dokploy/traefik/dynamic";
const OUT = path.join(DIR, "dokploy-plus.yml");
const SELF_URL = process.env.SELF_URL || "http://dokploy-plus:3000";
const DOKPLOY_RE = /^https?:\/\/dokploy:3000\/?$/;

export const state = { status: "starting", detail: null, hosts: [], file: OUT };

function readYaml(file) {
  try { return yamlLoad(readFileSync(file, "utf8")) || {}; } catch { return null; }
}

// Routers serving the Dokploy dashboard, from Dokploy's own file (or any file but ours).
function findDokployRouters() {
  const files = [path.join(DIR, "dokploy.yml"), ...safeList(DIR).filter((f) => f.endsWith(".yml") && f !== "dokploy.yml" && f !== "dokploy-plus.yml").map((f) => path.join(DIR, f))];
  for (const file of files) {
    const doc = readYaml(file);
    const http = doc?.http;
    if (!http?.routers || !http?.services) continue;
    const services = Object.entries(http.services)
      .filter(([, s]) => (s?.loadBalancer?.servers || []).some((x) => DOKPLOY_RE.test(x?.url || "")))
      .map(([name]) => name);
    if (!services.length) continue;
    const routers = Object.entries(http.routers).filter(([, r]) => services.includes(r?.service));
    if (routers.length) return { file, service: services[0], routers };
  }
  return null;
}

function safeList(dir) {
  try { return readdirSync(dir); } catch { return []; }
}

const isRedirect = (mw) => /redirect/i.test(mw);

export function render() {
  const found = findDokployRouters();
  if (!found) return { ok: false, reason: existsSync(DIR) ? "no-domain" : "no-traefik-dir" };
  const routers = {};
  let i = 0;
  const hosts = [];
  for (const [, r] of found.routers) {
    const mws = (r.middlewares || []).filter((m) => !isRedirect(m));
    // A router that only redirects HTTP -> HTTPS must stay Dokploy's: we don't mirror it.
    if ((r.middlewares || []).some(isRedirect)) continue;
    for (const m of String(r.rule).matchAll(/Host\(`([^`]+)`\)/g)) hosts.push(m[1]);
    const base = { entryPoints: r.entryPoints, ...(r.tls ? { tls: r.tls } : {}), ...(mws.length ? { middlewares: mws } : {}) };
    routers[`dokploy-plus-html-${i}`] = { ...base, rule: `(${r.rule}) && Method(\`GET\`) && HeaderRegexp(\`Accept\`, \`text/html\`)`, service: "dokploy-plus-failover", priority: 1000 };
    routers[`dokploy-plus-ext-${i}`] = { ...base, rule: `(${r.rule}) && PathPrefix(\`/_ext/\`)`, service: "dokploy-plus", priority: 1001 };
    i++;
  }
  if (!i) return { ok: false, reason: "no-router" };
  const doc = {
    http: {
      routers,
      services: {
        "dokploy-plus": { loadBalancer: { passHostHeader: true, servers: [{ url: SELF_URL }], healthCheck: { path: "/_ext/health", interval: "2s", timeout: "1s" } } },
        "dokploy-plus-failover": { failover: { service: "dokploy-plus", fallback: `${found.service}@file` } },
      },
    },
  };
  // JSON is valid YAML: no serializer needed.
  const text = `# Generated by Dokploy Plus from ${path.basename(found.file)} — removed automatically when the container stops.\n${JSON.stringify(doc, null, 2)}\n`;
  return { ok: true, text, hosts: [...new Set(hosts)] };
}

function writeIfChanged(text) {
  let cur = null;
  try { cur = readFileSync(OUT, "utf8"); } catch {}
  if (cur === text) return false;
  const tmp = `${OUT}.tmp`;
  writeFileSync(tmp, text, { mode: 0o644 });
  renameSync(tmp, OUT);
  return true;
}

export function sync() {
  if (process.env.TRAEFIK === "off") {
    Object.assign(state, { status: "disabled", detail: "TRAEFIK=off", hosts: [] });
    return;
  }
  try {
    const r = render();
    if (!r.ok) {
      remove();
      Object.assign(state, { status: "inactive", detail: r.reason, hosts: [] });
      return;
    }
    if (writeIfChanged(r.text)) console.log(`[traefik] route written for ${r.hosts.join(", ") || "Dokploy"} -> ${OUT}`);
    Object.assign(state, { status: "active", detail: null, hosts: r.hosts });
  } catch (e) {
    Object.assign(state, { status: "error", detail: e.message });
    console.error("[traefik]", e.message);
  }
}

export function remove() {
  try { unlinkSync(OUT); console.log(`[traefik] route removed (${OUT})`); } catch {}
}

export function start() {
  sync();
  // Dokploy rewrites dokploy.yml when the domain changes: follow it.
  setInterval(sync, 30_000).unref();
  const stop = () => { if (process.env.TRAEFIK !== "off") remove(); process.exit(0); };
  process.on("SIGTERM", stop);
  process.on("SIGINT", stop);
}
